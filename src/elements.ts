/** 原子番号から周期・族・系列を求める */
function position(z: number): Pick<Element, "period" | "group" | "series"> {
  const p = (period: number, group: number | null, series: Series | null = null) => ({
    period,
    group,
    series,
  });
  if (z === 1) return p(1, 1);
  if (z === 2) return p(1, 18);
  if (z <= 10) return p(2, z <= 4 ? z - 2 : z + 8);
  if (z <= 18) return p(3, z <= 12 ? z - 10 : z);
  if (z <= 36) return p(4, z - 18);
  if (z <= 54) return p(5, z - 36);
  if (z <= 56) return p(6, z - 54);
  if (z <= 71) return p(6, null, "lanthanoid");
  if (z <= 86) return p(6, z - 68);
  if (z <= 88) return p(7, z - 86);
  if (z <= 103) return p(7, null, "actinoid");
  return p(7, z - 100);
}

export const ELEMENTS: readonly Element[] = RAW.map(([symbol, nameJa, reading], i) => {
  const z = i + 1;
  return { z, symbol, nameJa, ...(reading ? { reading } : {}), ...position(z) };
});
